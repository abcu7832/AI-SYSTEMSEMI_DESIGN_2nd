`timescale 1ns / 1ps

module ROM (
    input  logic [31:0] addr,
    output logic [31:0] data
);

    logic [31:0] rom[0:61];

    initial begin
        //rom[x]=32'b func7 _ rs2 _ rs1 _f3 _ rd  _  op      //   R-Type
        rom[0] = 32'b0000000_00001_00010_000_00100_0110011;  //add x4, x2, x1
        rom[1] = 32'b0100000_00001_00010_000_00101_0110011;  //sub x5, x2, x1
        rom[2] = 32'b0000000_00001_00010_110_00100_0110011;  //or x4, x2, x1
        rom[3] = 32'b0000000_00001_00010_111_00101_0110011;  //and x5, x2, x1

        //rom[x]=32'b imm7  _ rs2 _ rs1 _ f3_ imm5_   op     //  S-Type mem[]
        rom[4] = 32'b0000000_00001_00001_010_00001_0100011;  // sb mem[(x1 + 1)>>2] = x0
        rom[5] = 32'b0000000_11111_00010_000_00010_0100011;  // sb mem[(12 + 2)>>2] = x31
        rom[6] = 32'b0000000_11111_00011_001_00011_0100011;  // sh mem[(13 + 3)>>2] = x31
        rom[7] = 32'b0000000_11111_00110_010_00100_0100011;  // sw mem[(13 + 4)>>2] = x31

        //rom[x]=32'b    imm12   _ rs1 _ f3_ rd  _   op   //   I-Type
        //or    =32'b func7 _shamt_ rs1 _ f3_ rd  _   op
        rom[8] = 32'b000000000001_00010_000_01001_0010011;// addi x9, x2, 1
        rom[9] = 32'b000000000001_00010_010_01001_0010011;// slti x9, x2, 1
        rom[10] = 32'b000000000001_00010_011_01001_0010011;// sltiu x9, x2, 1
        rom[11] = 32'b000000000001_00010_100_01001_0010011;// xori x9, x2, 1
        rom[12] = 32'b000000000001_00010_110_01001_0010011;// ori x9, x2, 1 
        rom[13] = 32'b000000000001_00010_111_01001_0010011;// andi x9, x2, 1 
        rom[14] = 32'b0000000_00001_00010_001_01001_0010011;// slli x9, x2, 1 
        rom[15] = 32'b0000000_00001_00010_101_01001_0010011;// srli x9, x2, 1
        rom[16] = 32'b0100000_00001_00010_101_01001_0010011;// srai x9, x2, 1

        //rom[x]= 32'b    imm12   _ rs1 _ f3_ rd  _   op   //   L-Type
        rom[17] = 32'b000000010100_00000_000_01000_0000011;// lb x8 = mem[5][0:7] 
        rom[18] = 32'b000000010100_00000_001_01000_0000011;// lh x8 = mem[5][0:15]
        rom[19] = 32'b000000010100_00000_010_01000_0000011;// lw x8 = mem[5][0:31]
        rom[20] = 32'b000000000000_00000_100_01000_0000011;// lbu x8 = mem[0][0:7] 
        rom[21] = 32'b000000000000_00000_101_01000_0000011;// lhu x8 = mem[0][0:15]
    end

    assign data = rom[addr[31:2]];
endmodule
