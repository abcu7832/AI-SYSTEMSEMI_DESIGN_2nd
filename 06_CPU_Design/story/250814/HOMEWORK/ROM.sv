`timescale 1ns / 1ps

module ROM (
    input  logic [31:0] addr,
    output logic [31:0] data
);

    logic [31:0] rom[0:61];

    initial begin
        //rom[x]=32'b func7 _ rs2 _ rs1 _fu3_ rd  _ op
        rom[0] = 32'b0000000_00001_00010_000_00100_0110011;//add x4, x2, x1
        rom[1] = 32'b0100000_00001_00010_000_00101_0110011;//sub x5, x2, x1
        rom[2] = 32'b0000000_00000_00011_001_00110_0110011;//sll x6, x3, x0
        rom[3] = 32'b0000000_00000_00011_101_00111_0110011;//srl x7, x3, x0
        rom[4] = 32'b0100000_00001_00010_101_00100_0110011;//sra x4, x2, x1
        rom[5] = 32'b0000000_00001_00010_010_00101_0110011;//slt x5, x2, x1
        rom[6] = 32'b0000000_00000_00011_011_00110_0110011;//sltu x6, x3, x0
        rom[7] = 32'b0000000_00000_00011_100_00111_0110011;//xor x7, x3, x0        
        rom[8] = 32'b0000000_00001_00010_110_00100_0110011;//or x4, x2, x1
        rom[9] = 32'b0000000_00001_00010_111_00101_0110011;//and x5, x2, x1                                              
    end

    assign data = rom[addr[31:2]];
endmodule
